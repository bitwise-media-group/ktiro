// Demo intents for Ledgerline. Each is a projection of
// ktiro-intents/intents/<id>-<slug>/ (intent.md, plan.md, hil/*.md, runs/*.md).
//
// The set is shaped to show the system's rules at work: every phase sits at
// or under its WIP limit (engineering is full, so an approved plan queues),
// two merge sets are deployed dark and waiting in business review, a net-new
// ADR waits for agreement in technical review, a planning-time ADR change
// faces its burden of proof, a canary is mid burn-in, a fast-path intent is
// removing a fully rolled-out flag, and each demo persona has something
// waiting on them.

import type { AgentId, Card, Gate, Intent, Message, Phase, PhaseRecord, Speaker } from "../types";
import { hoursAgo } from "./org";

export const GATE_DEFS: Pick<Gate, "from" | "to" | "name">[] = [
  { from: "defining", to: "planning", name: "Intent accepted" },
  { from: "planning", to: "engineering", name: "Plan approved" },
  { from: "engineering", to: "technical", name: "Ready for review" },
  { from: "technical", to: "business", name: "Technically sound" },
  { from: "business", to: "operate", name: "Results accepted" },
  { from: "operate", to: "done", name: "Outcome confirmed" },
];

export function gates(states: Gate["state"][], extra: Partial<Gate>[] = []): Gate[] {
  return GATE_DEFS.map((d, i) => ({ ...d, state: states[i] ?? "upcoming", ...(extra[i] ?? {}) }));
}

function P(
  phase: Phase,
  enteredH: number,
  exitedH: number | undefined,
  queuedH: number,
  activeH: number,
  hilH: number,
  costUsd: number,
  tokensM: number,
  hilCount = 0,
): PhaseRecord {
  return {
    phase,
    enteredAt: hoursAgo(enteredH),
    exitedAt: exitedH === undefined ? undefined : hoursAgo(exitedH),
    queuedH,
    activeH,
    hilH,
    costUsd,
    tokensM,
    hilCount,
  };
}

let seq = 0;
const ag = (id: AgentId): Speaker => ({ kind: "agent", id });
const pe = (id: string): Speaker => ({ kind: "person", id });
const sys: Speaker = { kind: "system" };
function M(atH: number, from: Speaker, phase: Phase, body?: string, card?: Card): Message {
  return { id: `m${++seq}`, at: hoursAgo(atH), from, phase, body, card };
}
