function done(
  id: string,
  slug: string,
  title: string,
  kind: Intent["kind"],
  value: number,
  author: string,
  repos: string[],
  createdH: number,
  doneH: number,
  phaseH: number[],
  cost: number,
  finding?: Intent["finding"],
): Intent {
  let t = createdH;
  const total = phaseH.reduce((a, b) => a + b, 0);
  const phases: PhaseRecord[] = (["defining", "planning", "engineering", "technical", "business", "operate"] as Phase[])
    .map((ph, i) => {
      const span = phaseH[i];
      const rec = P(ph, t, t - span, span * 0.2, span * 0.6, span * 0.2, (cost * span) / total, cost / 20, i === 4 && span > 0 ? 1 : 0);
      t -= span;
      return span > 0 ? rec : null;
    })
    .filter((r): r is PhaseRecord => r !== null);
  const noBusiness = phaseH[4] === 0;
  return {
    id,
    slug,
    title,
    kind,
    kindReason: "",
    value: { amount: value, basis: "", confidence: 0.6 },
    importance: "normal",
    author,
    contributors: [],
    origin: finding ? "security" : undefined,
    finding,
    phase: "done",
    status: "complete",
    statusText: `Outcome confirmed · flag removed · ${Math.round((createdH - doneH) / 24)}d end to end`,
    repos,
    dependsOn: [],
    createdAt: hoursAgo(createdH),
    request: "",
    outcome: [],
    sizing: { estTurns: 100, contextFit: 0.4 },
    phases,
    gates: gates(["approved", "auto-skipped", "auto-skipped", "auto-skipped", noBusiness ? "auto-skipped" : "approved", "auto-skipped"], [
      {},
      {},
      {},
      {},
      noBusiness ? { why: "No customer-visible change: infrastructure only." } : {},
    ]),
    messages: [],
  };
}
